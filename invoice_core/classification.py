# Safe fallback when the AI gives nothing usable: the most common choice per side.
DEFAULTS = {
    "income": ("category1_3", "E3_561_001"),
    "expense": ("category2_4", "E3_585_016"),
}


def lists_for(direction: str) -> tuple:
    if direction == "income":
        return INCOME_CATEGORIES, INCOME_TYPES
    return EXPENSE_CATEGORIES, EXPENSE_TYPES


def prompt_text() -> str:
    """Compact code list for the extraction prompt."""
    def block(title, d):
        return title + ":\n" + "\n".join(f"{k} = {v}" for k, v in d.items())
    return "\n\n".join([
        block("[INCOME] categories", INCOME_CATEGORIES), block("[INCOME] E3 types", INCOME_TYPES),
        block("[EXPENSE] categories", EXPENSE_CATEGORIES), block("[EXPENSE] E3 types", EXPENSE_TYPES),
    ])


def clean(direction: str, category, e3) -> tuple:
    """Keep only official codes for the right side; fall back to the default."""
    categories, types = lists_for(direction)
    default_cat, default_e3 = DEFAULTS["income" if direction == "income" else "expense"]
    category = category if category in categories else default_cat
    e3 = e3 if e3 in types else default_e3
    return category, e3


def options() -> dict:
    """For the frontend dropdowns."""
    def opts(d):
        return [{"code": k, "label": v} for k, v in d.items()]
    return {
        "income": {"categories": opts(INCOME_CATEGORIES), "types": opts(INCOME_TYPES)},
        "expense": {"categories": opts(EXPENSE_CATEGORIES), "types": opts(EXPENSE_TYPES)},
    }
